#!/usr/bin/perl
# fon2fw.pl - convert Windows .FON fonts to ARC firmware font tables (the
# Jazz vgaoem.obj/8514oem.obj): per character from 1 to 255, the rows of the
# glyph, (width + 7) / 8 bytes each, the leftmost pixel in bit 0.
#
#   perl fon2fw.pl NAME FILE.FON [NAME FILE.FON]... > fwfonts.c
use strict;

sub fnt {
    my $f = shift;
    open my $h, '<:raw', $f or die "$f: $!";
    local $/;
    my $d = <$h>;
    my $ne = unpack 'V', substr($d, 0x3c, 4);
    die "$f: not NE" unless substr($d, $ne, 2) eq 'NE';
    my $rt = $ne + unpack('v', substr($d, $ne + 0x24, 2));
    my $shift = unpack 'v', substr($d, $rt, 2);
    my $p = $rt + 2;
    while (1) {
        my ($type, $count) = unpack 'vv', substr($d, $p, 4);
        die "$f: no font" unless $type;
        $p += 8;
        if ($type == 0x8008) {
            my ($off, $len) = unpack 'vv', substr($d, $p, 4);
            return substr($d, $off << $shift, $len << $shift);
        }
        $p += 12 * $count;
    }
}

print "/* Generated by tools/fon2fw.pl. */\n\n";
while (@ARGV) {
    my ($name, $file) = splice @ARGV, 0, 2;
    my $f = fnt($file);
    my ($ver, $height, $first, $last, $default) =
        (unpack('v', $f), unpack('v', substr($f, 88, 2)), unpack('CCC', substr($f, 95, 3)));
    my $width = unpack 'v', substr($f, 93, 2);
    my $bytes = int(($width + 7) / 8);
    my $table = $ver >= 0x300 ? 148 : 118;
    printf "unsigned char %s[255 * %d] = {\n", $name, $height * $bytes;
    for my $c (1 .. 255) {
        my $g = ($c < $first || $c > $last) ? $default : $c - $first;
        my $e = $table + $g * ($ver >= 0x300 ? 6 : 4);
        my $w = unpack 'v', substr($f, $e, 2);
        my $o = $ver >= 0x300 ? unpack('V', substr($f, $e + 2, 4)) : unpack('v', substr($f, $e + 2, 2));
        my @out;
        for my $r (0 .. $height - 1) {
            for my $b (0 .. $bytes - 1) {
                my $v = $b < int(($w + 7) / 8) ? ord(substr($f, $o + $b * $height + $r, 1)) : 0;
                my $x = 0;
                $x |= (($v >> (7 - $_)) & 1) << $_ for 0 .. 7;
                push @out, sprintf '0x%02x', $x;
            }
        }
        print "    ", join(', ', @out), ",\n";
    }
    print "};\n\n";
}
