; Module Name:
;
;    glarmapi.asm
;
; Abstract:
;
;    The OpenGL API entries of the OpenGL client DLL: the ARM port of
;    OPENGL\CLIENT\MIPS\GLMAPI.S. An entry jumps through the dispatch table of
;    the rendering context current on the thread: a function of the fast table
;    of the TEB (one dispindx.h gives a FASTINDEX) through that table, any other
;    through the whole table that starts the OpenGL data of the thread, which
;    its TLS slot points to (dwTlsOffset from the TEB). The arguments stay as
;    the caller left them, in r0 - r3, the VFP registers and on the stack: an
;    entry uses r12 and keeps r0 on the stack while it borrows it.
;
;--

#include "ksarm.h"
#include "kxarm.h"
#include "dispindx.h"

        IMPORT  dwTlsOffset

;
; OPENGLAPI(Name) is GLENTRY Name, FASTINDEX_Name, INDEX_Name after the C
; preprocessor: the fast index is a number, or its own name when the function
; has none.
;

#define GLENTRY1(Name, Fast) GLENTRY Name, Fast, INDEX_##Name
#define GLENTRY2(Name, Fast) GLENTRY1(Name, Fast)
#define OPENGLAPI(Name) GLENTRY2(Name, FASTINDEX_##Name)

        MACRO
        GLENTRY $Name, $Fast, $Index

        LEAF_ENTRY $Name
        IF "$Fast" :LEFT: 10 = "FASTINDEX_"
        push    {r0}
        mrc     p15, 0, r12, c13, c0, 2         ; TEB
        ldr     r0, =dwTlsOffset
        ldr     r0, [r0]                        ; offset of the TLS slot
        ldr     r12, [r12, r0]                  ; OpenGL data of the thread
        pop     {r0}
        ldr     pc, [r12, #($Index) * 4]        ; whole dispatch table
        ELSE
        mrc     p15, 0, r12, c13, c0, 2         ; TEB
        ldr     pc, [r12, #TeglDispatchTable + ($Fast) * 4] ; fast table
        ENDIF
        LEAF_END $Name

        MEND

